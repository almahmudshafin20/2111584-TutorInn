-- Audited, explicitly accepted First Admin ownership transfer. Browser roles get no access.
CREATE TABLE IF NOT EXISTS public.first_admin_transfers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    initiated_by_account_id integer NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    recipient_account_id integer NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    status varchar(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'declined', 'cancelled', 'expired')),
    created_at varchar(40) NOT NULL,
    expires_at varchar(40) NOT NULL,
    responded_at varchar(40)
);
CREATE INDEX IF NOT EXISTS ix_first_admin_transfers_initiated_by ON public.first_admin_transfers(initiated_by_account_id);
CREATE INDEX IF NOT EXISTS ix_first_admin_transfers_recipient ON public.first_admin_transfers(recipient_account_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_first_admin_transfers_one_pending
    ON public.first_admin_transfers(status) WHERE status = 'pending';

ALTER TABLE public.first_admin_transfers ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.first_admin_transfers FROM PUBLIC, anon, authenticated;
