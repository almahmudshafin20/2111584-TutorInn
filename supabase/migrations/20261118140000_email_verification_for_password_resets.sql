-- Email ownership proof required before password-reset requests can be reviewed.
ALTER TABLE public.user_accounts ADD COLUMN IF NOT EXISTS email_verified_at varchar(40);

CREATE TABLE IF NOT EXISTS public.email_verification_tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    email varchar(255) NOT NULL,
    token_hash varchar(64) NOT NULL UNIQUE,
    created_at varchar(40) NOT NULL,
    expires_at varchar(40) NOT NULL,
    used_at varchar(40),
    invalidated_at varchar(40)
);
CREATE INDEX IF NOT EXISTS ix_email_verification_tokens_account_id ON public.email_verification_tokens(account_id);
CREATE INDEX IF NOT EXISTS ix_email_verification_tokens_expires_at ON public.email_verification_tokens(expires_at);
ALTER TABLE public.email_verification_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.email_verification_tokens FROM PUBLIC, anon, authenticated;
