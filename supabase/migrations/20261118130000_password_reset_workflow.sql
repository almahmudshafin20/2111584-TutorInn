-- Approved, user-controlled password reset. Raw reset tokens are never stored.
CREATE TABLE IF NOT EXISTS public.password_reset_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    account_email varchar(255) NOT NULL,
    account_role varchar(16) NOT NULL CHECK (account_role IN ('student', 'tutor')),
    status varchar(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected', 'completed')),
    requested_at varchar(40) NOT NULL,
    requested_ip varchar(64) NOT NULL DEFAULT '',
    requested_user_agent varchar(512) NOT NULL DEFAULT '',
    reviewed_by_account_id integer REFERENCES public.user_accounts(id) ON DELETE SET NULL,
    reviewed_at varchar(40),
    review_note varchar(1000) NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ix_password_reset_requests_status_requested
    ON public.password_reset_requests(status, requested_at);
CREATE INDEX IF NOT EXISTS ix_password_reset_requests_account_status
    ON public.password_reset_requests(account_id, status);

CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id integer NOT NULL REFERENCES public.password_reset_requests(id) ON DELETE CASCADE,
    account_id integer NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL UNIQUE,
    created_at varchar(40) NOT NULL,
    expires_at varchar(40) NOT NULL,
    used_at varchar(40),
    invalidated_at varchar(40)
);
CREATE INDEX IF NOT EXISTS ix_password_reset_tokens_request_id ON public.password_reset_tokens(request_id);
CREATE INDEX IF NOT EXISTS ix_password_reset_tokens_account_id ON public.password_reset_tokens(account_id);
CREATE INDEX IF NOT EXISTS ix_password_reset_tokens_expires_at ON public.password_reset_tokens(expires_at);

ALTER TABLE public.password_reset_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.password_reset_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.password_reset_requests FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.password_reset_tokens FROM PUBLIC, anon, authenticated;
